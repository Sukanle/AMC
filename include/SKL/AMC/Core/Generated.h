#ifndef AMC_CORE_GENERATED_H
#define AMC_CORE_GENERATED_H

// Warning banner emitted at the top of every AMC-generated file (similar to
// Qt's MOC). It lives in Core rather than in a single language backend so that
// every generator — the language backends (`AMC/src/Lang/*`) and the Core
// generators (`Adapter.cpp`, `Lua.cpp`) — shares one wording and one place to
// change it.
//
// Design principle: the shared macro only answers "what is this file, why must
// I not edit it, and where should I change instead". Generator identity, ABI
// target information, and file-purpose explanations belong in file-specific
// comments that follow this banner, not in the macro itself.
//
// The comment marker is a macro parameter rather than a hard-coded `//`, so
// every generator spells its own output language's comment syntax:
//
//   AMC_GENERATED_FILE_WARNING("//")   // C++ / Rust / Zig
//   AMC_GENERATED_FILE_WARNING("--")   // Lua
//
// Expanding to a run of adjacent string literals means it can be concatenated
// (or streamed) directly into a larger emission call. The trailing marker line
// separates the banner from the file-specific comments that follow.
#define AMC_GENERATED_FILE_WARNING(comment)                                                                         \
    comment " This file was automatically generated by AMC.\n" comment " DO NOT EDIT THIS FILE MANUALLY.\n" comment \
            " Changes will be overwritten when this file is regenerated.\n" comment                                 \
            " Modify the source declarations or generation configuration instead.\n" comment "\n"

#endif   // AMC_CORE_GENERATED_H
