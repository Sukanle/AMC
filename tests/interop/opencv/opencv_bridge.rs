// Rust bridge surface for OpenCV.
//
// The bridge owns an OpenCV `cv::Mat` behind a raw handle, exposes ordinary
// `&Mat` / `&mut Mat` borrows, and keeps `OpencvMat` `#[repr(C)]` so AMC can
// lower `Box<OpencvMat>` into an ABIX owner handle.

mod opencv_shim_ffi;

use opencv_shim_ffi::*;

#[repr(C)]
pub struct OpencvMat {
    pub handle: *mut core::ffi::c_void,
}

impl Drop for OpencvMat {
    fn drop(&mut self) {
        if !self.handle.is_null() {
            unsafe { opencv_shim_mat_destroy(self.handle) };
        }
    }
}

pub fn opencv_mat_new(rows: i32, cols: i32) -> Box<OpencvMat> {
    let handle = unsafe { opencv_shim_mat_new(rows, cols) };
    assert!(!handle.is_null(), "OpenCV Mat allocation failed");
    Box::new(OpencvMat { handle })
}

pub fn opencv_mat_set(mat: &mut OpencvMat, row: i32, col: i32, value: f64) -> i32 {
    unsafe { opencv_shim_mat_set(mat.handle, row, col, value) }
}

pub fn opencv_mat_get(mat: &OpencvMat, row: i32, col: i32) -> f64 {
    unsafe { opencv_shim_mat_get(mat.handle, row, col) }
}

pub fn opencv_mat_sum(mat: &OpencvMat) -> f64 {
    unsafe { opencv_shim_mat_sum(mat.handle) }
}

