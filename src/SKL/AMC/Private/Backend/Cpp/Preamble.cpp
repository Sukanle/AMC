namespace skl::amc::lang::backend::cpp {

int Emit::preamble(std::string &error) {
    _o.print("#pragma once\n");
    _o.print(AMC_GENERATED_FILE_WARNING("//"));
    _o.print("// Generated by `amc generate -l cpp`.\n");
    _o.print(
        "#include <SKL/ABIX/Runtime/Registry.h>\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n"
        "#include <string.h>\n");
    // The interface contract constants and typed signature table below name
    // `InterfaceId` / `mics::util::array`, so pull in those headers only when the
    // module actually declares interfaces; the proxy API is added only when a
    // proxy class is actually generated.
    bool any_interface_proxy = false;
    for (const auto &record : _m.interfaces)
        if (interface_has_handle_methods(_m, record)) {
            any_interface_proxy = true;
            break;
        }
    if (!_m.interfaces.empty()) {
        _o.print("#include <SKL/MICS/Util/Array.h>\n");
        _o.print("#include <SKL/ABIX/Interface/Contract.h>\n");
    }
    if (any_interface_proxy) _o.print("#include <SKL/ABIX/Interface/Proxy.h>\n");

    std::string prologue;
    if (!amc::backend::read_codein_text("Cpp/Prologue.hpp", prologue, error)) return 1;
    _o.print("{}", prologue);
    return 0;
}

}   // namespace skl::amc::lang::backend::cpp
