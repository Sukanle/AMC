//! Provider crate for the AMC Rust workspace example.
//!
//! The `extern "C"` surface is generated from these ordinary Rust functions.
//! `amc build` writes `generated/widget_thunks.rs`; the example compiles the
//! thunks into this crate so Cargo and AMC share one source of truth.

use std::sync::atomic::{AtomicUsize, Ordering};

static LIVE: AtomicUsize = AtomicUsize::new(0);

#[repr(C)]
pub struct Widget {
    pub value: i32,
}

impl Drop for Widget {
    fn drop(&mut self) {
        LIVE.fetch_sub(1, Ordering::SeqCst);
    }
}

pub fn widget_make(value: i32) -> Box<Widget> {
    LIVE.fetch_add(1, Ordering::SeqCst);
    Box::new(Widget { value })
}

pub fn widget_value(widget: Box<Widget>) -> i32 {
    widget.value
}

pub fn widget_live() -> usize {
    LIVE.load(Ordering::SeqCst)
}

// Generated by `amc build -c amc.abic.toml`.
include!("generated/widget_thunks.rs");
